# Converts SDL's precompiled SPIR-V shader headers for the GPU render backend
# (.ref/SDL/src/render/gpu/shaders/*.spv.h, produced by build-shaders.sh with
# shadercross) into Zig byte arrays for src/render/gpu/shader_blobs.zig.
#
# Each `static const unsigned char NAME_spv[] = { ... };` array becomes a
# `pub const NAME: []const u8 = &.{ ... };`. The SPIR-V stays unchanged; the
# Vulkan backend copies it into word-aligned storage at module creation.
# Only the SPIR-V (Vulkan) headers are converted; DXIL, MSL and the private
# blobs belong to other backends and are not emitted.
#
# Usage: python3 -I render_gpu_shaders.py <path to .ref/SDL>
#        > src/render/gpu/shader_blobs.zig
import os
import re
import sys

root = os.path.join(sys.argv[1], "src", "render", "gpu", "shaders")

# SDL header stem -> Zig identifier.
blobs = [
    ("linepoint.vert.spv.h", "linepoint_vert"),
    ("tri_color.vert.spv.h", "tri_color_vert"),
    ("tri_texture.vert.spv.h", "tri_texture_vert"),
    ("color.frag.spv.h", "color_frag"),
    ("texture_rgb.frag.spv.h", "texture_rgb_frag"),
    ("texture_rgba.frag.spv.h", "texture_rgba_frag"),
    ("texture_advanced.frag.spv.h", "texture_advanced_frag"),
]

print("//! Generated by tools/gen/render_gpu_shaders.py from SDL's precompiled SPIR-V")
print("//! shader headers (src/render/gpu/shaders). Do not edit by hand.")
print("//!")
print("//! Each blob is a complete SPIR-V module as shipped by SDL; its byte length is")
print("//! a multiple of four and its first word is the SPIR-V magic number.")
print("")

for filename, name in blobs:
    text = open(os.path.join(root, filename), encoding="utf-8").read()
    match = re.search(r"static const unsigned char \w+\[\]\s*=\s*\{(.*?)\};", text, flags=re.S)
    if match is None:
        sys.exit(f"no byte array in {filename}")
    values = re.findall(r"0x([0-9a-fA-F]{2})", match.group(1))
    if len(values) % 4 != 0:
        sys.exit(f"{filename}: byte count {len(values)} is not a whole number of words")
    print(f"/// SDL `{filename}` ({len(values)} bytes).")
    print(f"pub const {name}: []const u8 = &.{{")
    for start in range(0, len(values), 16):
        chunk = ", ".join(f"0x{v.lower()}" for v in values[start:start + 16])
        print(f"    {chunk},")
    print("};")
    print("")
