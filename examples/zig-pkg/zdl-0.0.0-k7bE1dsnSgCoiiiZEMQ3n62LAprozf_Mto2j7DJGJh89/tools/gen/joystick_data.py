#!/usr/bin/env python3
"""One-off generator: SDL controller table and Linux gamepad mapping database -> Zig data.

Run as: python3 -I tools/gen/joystick_data.py <zdl_root>
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
sdl = root / ".ref/SDL/src/joystick"
out = root / "src/joystick"

# SDL k_eControllerType_* suffix -> Zig tag of joystick/controller_type.zig.
TYPE_TAGS = {
    "UnknownSteamController": "unknown_steam_controller",
    "SteamController": "steam_controller",
    "SteamControllerV2": "steam_controller_v2",
    "SteamControllerNeptune": "steam_controller_neptune",
    "SteamControllerTriton": "steam_controller_triton",
    "UnknownNonSteamController": "unknown_non_steam_controller",
    "XBox360Controller": "xbox360_controller",
    "XBoxOneController": "xbox_one_controller",
    "PS3Controller": "ps3_controller",
    "PS4Controller": "ps4_controller",
    "WiiController": "wii_controller",
    "AppleController": "apple_controller",
    "AndroidController": "android_controller",
    "SwitchProController": "switch_pro_controller",
    "SwitchJoyConLeft": "switch_joycon_left",
    "SwitchJoyConRight": "switch_joycon_right",
    "SwitchJoyConPair": "switch_joycon_pair",
    "SwitchInputOnlyController": "switch_input_only_controller",
    "MobileTouch": "mobile_touch",
    "XInputSwitchController": "xinput_switch_controller",
    "PS5Controller": "ps5_controller",
    "XBoxEliteController": "xbox_elite_controller",
    "XInputPS4Controller": "xinput_ps4_controller",
    "PS5EdgeController": "ps5_edge_controller",
    "HoriSteamController": "hori_steam_controller",
    "8BitDoController": "bitdo8_controller",
    "Switch2ProController": "switch2_pro_controller",
    "Switch2InputOnlyController": "switch2_input_only_controller",
}

entry_re = re.compile(
    r'^\s*\{\s*MAKE_CONTROLLER_ID\s*\(\s*0[xX]([0-9a-fA-F]+)\s*,\s*0[xX]([0-9a-fA-F]+)\s*\)\s*,'
    r'\s*k_eControllerType_(\w+)\s*,\s*(NULL|"([^"]*)")\s*\}'
)

seen = {}
for line in (sdl / "controller_list.h").read_text(encoding="utf-8").splitlines():
    if line.lstrip().startswith("//"):
        continue
    m = entry_re.match(line)
    if not m:
        continue
    vid, pid, kind, _, name = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
    if kind not in TYPE_TAGS:
        raise SystemExit(f"unmapped controller type {kind}")
    ident = (int(vid, 16) << 16) | int(pid, 16)
    if ident in seen:  # SDL's linear lookup returns the first entry.
        continue
    seen[ident] = (TYPE_TAGS[kind], name)

lines = [
    "//! Controller vendor/product classification table. Generated by a one-off",
    "//! script from SDL's controller_list.h; do not edit by hand.",
    "//! Keys are (vendor << 16) | product, sorted ascending; the first SDL entry",
    "//! for each id is kept, matching SDL's first-match lookup.",
    "const controller_type = @import(\"controller_type.zig\");",
    "const ControllerType = controller_type.ControllerType;",
    "",
    "pub const Entry = struct {",
    "    id: u32,",
    "    kind: ControllerType,",
    "    /// Optional product name that SDL uses for this id.",
    "    name: ?[]const u8,",
    "};",
    "",
    f"pub const entries = [_]Entry{{",
]
for ident in sorted(seen):
    tag, name = seen[ident]
    name_text = "null" if name is None or name == "" and False else (f'"{name}"' if name is not None else "null")
    lines.append(f"    .{{ .id = 0x{ident:08x}, .kind = .{tag}, .name = {name_text} }},")
lines.append("};")
(out / "controller_table.zig").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("controller entries:", len(seen))

# Linux mapping database: the SDL_JOYSTICK_LINUX block of SDL_gamepad_db.h.
db_lines = (sdl / "SDL_gamepad_db.h").read_text(encoding="utf-8").splitlines()
start = next(i for i, l in enumerate(db_lines) if l.startswith("#if defined(SDL_JOYSTICK_LINUX)"))
end = next(i for i in range(start + 1, len(db_lines)) if db_lines[i].startswith("#endif"))
entries = []
for l in db_lines[start + 1:end]:
    s = l.strip()
    if not s:
        continue
    if s.startswith("#"):
        raise SystemExit("unexpected preprocessor line inside Linux block: " + s)
    m = re.fullmatch(r'"([^"\\]*)",?\s*(/\*.*\*/)?', s)
    if not m:
        raise SystemExit("unexpected mapping line: " + s[:80])
    entries.append(m.group(1))

# Platform-independent entries outside any #if block (SDL keeps these everywhere).
depth = 0
independent = 0
for l in db_lines:
    s = l.strip()
    if s.startswith("#if"):
        depth += 1
    elif s.startswith("#endif"):
        depth -= 1
    elif depth == 0 and s.startswith('"'):
        independent += 1
if independent:
    raise SystemExit(f"found {independent} platform-independent entries; add them to the table")

glines = [
    "//! Built-in SDL gamepad mapping strings for Linux. Generated by a one-off",
    "//! script from SDL_gamepad_db.h (its SDL_JOYSTICK_LINUX block, the only one",
    "//! enabled on Linux; the block contains no platform: fields). Do not edit.",
    "",
    "pub const linux = [_][]const u8{",
]
for e in entries:
    if "\\" in e:
        raise SystemExit("escape in mapping string")
    glines.append(f'    "{e}",')
glines.append("};")
(out / "gamepad_db.zig").write_text("\n".join(glines) + "\n", encoding="utf-8")
print("linux mappings:", len(entries))
