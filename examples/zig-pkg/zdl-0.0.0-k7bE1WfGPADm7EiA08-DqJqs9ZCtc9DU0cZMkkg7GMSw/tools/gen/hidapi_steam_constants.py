# Evaluates every C enum in SDL's Valve Steam Controller protocol header and
# prints them as Zig constants (snake_case names, untyped integers), for
# src/joystick/hidapi/steam_constants.zig.
#
# Enumerators without an explicit value continue from the previous value, and
# aliases such as `IO_DIGITAL_BUTTON_Y=IO_DIGITAL_BUTTON_1` are evaluated against
# the names already defined in the same header. Entries whose names are not valid
# Zig identifiers are skipped (none are expected).
#
# Usage: python3 -I hidapi_steam_constants.py <path to steam/controller_constants.h>
#        > src/joystick/hidapi/steam_constants.zig
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
# Strip block and line comments so enumerator text is plain.
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)

values = {}
order = []

for body in re.findall(r"(?:typedef\s+)?enum\s*\w*\s*\{(.*?)\}", src, flags=re.S):
    next_value = 0
    for raw in body.split(","):
        entry = raw.strip()
        if not entry:
            continue
        if "=" in entry:
            name, expr = (part.strip() for part in entry.split("=", 1))
            # Substitute known names, then evaluate the integer expression.
            def repl(match):
                word = match.group(0)
                if word in values:
                    return str(values[word])
                return word
            text = re.sub(r"[A-Za-z_][A-Za-z_0-9]*", repl, expr)
            if not re.fullmatch(r"[-+()<>|&~*\s0-9a-fA-FxX]+", text):
                raise SystemExit(f"cannot evaluate {name} = {expr}")
            value = int(eval(text, {"__builtins__": {}}))
        else:
            name, value = entry, next_value
        if not re.fullmatch(r"[A-Z][A-Z_0-9]*", name):
            continue
        if name in values:
            continue
        values[name] = value
        order.append(name)
        next_value = value + 1

print("//! Generated by tools/gen/hidapi_steam_constants.py from")
print("//! .ref/SDL/src/joystick/hidapi/steam/controller_constants.h. Do not edit.")
print("//!")
print("//! Feature-report IDs, setting numbers, attribute tags, trackpad modes and")
print("//! digital-mapping inputs of the Valve Steam Controller protocol. The names are")
print("//! the C enumerators in snake_case; values are untyped integers so each call")
print("//! site picks the width it needs.")
print("")
for name in order:
    value = values[name]
    print(f"pub const {name.lower()} = {value};")
