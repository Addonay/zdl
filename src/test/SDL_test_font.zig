    if ((len > @as(usize, 0)) and (@as(c_int, text[len -% @as(usize, 1)]) == @as(c_int, '\n'))) {
        len -%= 1;
        newline = @"true" != 0;
    }
    if (textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))] != null) {
        existing = SDL_strlen(textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))]);
    } else {
        existing = 0;
    }
    if (@as(c_int, text.*) == @as(c_int, '\x08')) {
        if (existing != 0) {
            while ((existing > @as(usize, 1)) and ((@as(c_int, @as(Uint8, textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))][existing -% @as(usize, 1)])) >= @as(c_int, 128)) and (@as(c_int, @as(Uint8, textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))][existing -% @as(usize, 1)])) <= @as(c_int, 191)))) {
                existing -%= 1;
            }
            existing -%= 1;
            textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))][existing] = '\x00';
        } else if (textwin.*.current > @as(c_int, 0)) {
            SDL_free(@ptrCast(@alignCast(textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))])));
            textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))] = null;
            textwin.*.current -= 1;
        }
        return;
    }
    line = @ptrCast(@alignCast(SDL_realloc(@ptrCast(@alignCast(textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))])), (existing +% len) +% @as(usize, 1))));
    if (line != null) {
        _ = memcpy(@ptrCast(@alignCast(&line[existing])), @ptrCast(@alignCast(text)), len);
        line[existing +% len] = '\x00';
        textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))] = line;
        if (newline) {
            if (textwin.*.current == (textwin.*.numlines - @as(c_int, 1))) {
                SDL_free(@ptrCast(@alignCast(textwin.*.lines[@as(c_int, 0)])));
                _ = memmove(@ptrCast(@alignCast(&textwin.*.lines[@as(c_int, 0)])), @ptrCast(@alignCast(&textwin.*.lines[@as(c_int, 1)])), @as(c_ulong, @bitCast(@as(c_long, textwin.*.numlines - @as(c_int, 1)))) *% @sizeOf(@TypeOf(textwin.*.lines[@as(c_int, 1)])));
                textwin.*.lines[@bitCast(@as(isize, @intCast(textwin.*.current)))] = null;
            } else {
                textwin.*.current += 1;
            }
        }
    }
}
