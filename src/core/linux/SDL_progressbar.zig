    var desktop_path: [*c]u8 = @ptrCast(@alignCast(SDL_malloc_REAL(desktop_path_total_length)));
    _ = &desktop_path;
    if (!(desktop_path != null)) {
        return null;
    }
    desktop_path.* = '\x00';
    _ = SDL_strlcat_REAL(desktop_path, app_id, desktop_path_total_length);
    _ = SDL_strlcat_REAL(desktop_path, desktop_suffix, desktop_path_total_length);
    return desktop_path;
}
