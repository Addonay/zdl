#!/usr/bin/env python3
"""Generate src/image/webp_tables.zig: RFC 6386 VP8 key-frame probability and
quantizer tables plus the WebP lossless distance map. The values are the
normative RFC 6386 / RFC 9649 tables; the parser reads them from the
MIT/Apache-2.0 `image-webp` crate's `src/vp8.rs` and `src/lossless.rs` because
they hold them in one easily parsed place.

Usage: python3 -I tools/gen/webp_tables.py PATH/TO/image-webp/src \
           > src/image/webp_tables.zig && zig fmt src/image/webp_tables.zig
"""
import re
import sys

TABLES = [
    # name in vp8.rs, zig name, zig element type, shape, doc
    ("KEYFRAME_BPRED_MODE_PROBS", "bmode_probs", "u8", (10, 10, 9),
     "Key-frame subblock mode probabilities indexed [above][left][tree node]."),
    ("COEFF_UPDATE_PROBS", "coeff_update_probs", "u8", (4, 8, 3, 11),
     "Probabilities that a token probability is updated, [type][band][context][node]."),
    ("COEFF_PROBS", "default_coeff_probs", "u8", (4, 8, 3, 11),
     "Default token probabilities, [type][band][context][node]."),
    ("DC_QUANT", "dc_quant", "u16", (128,), "DC dequantization factors by quantizer index."),
    ("AC_QUANT", "ac_quant", "u16", (128,), "AC dequantization factors by quantizer index."),
]


def extract(source: str, name: str) -> list[int]:
    m = re.search(r"const " + name + r"\s*:[^=]*=\s*\[", source)
    if not m:
        raise SystemExit(f"{name} not found")
    depth, i = 1, m.end()
    while depth:
        depth += {"[": 1, "]": -1}.get(source[i], 0)
        i += 1
    return [int(v) for v in re.findall(r"-?\d+", source[m.end():i])]


def emit(values, shape, indent):
    if len(shape) == 1:
        return "." + "{ " + ", ".join(map(str, values)) + " }"
    step = len(values) // shape[0]
    inner = [emit(values[k * step:(k + 1) * step], shape[1:], indent + 1) for k in range(shape[0])]
    pad = "    " * (indent + 1)
    return ".{\n" + "".join(f"{pad}{x},\n" for x in inner) + "    " * indent + "}"


def main():
    source = open(sys.argv[1] + "/vp8.rs", encoding="utf-8").read()
    out = ["//! Generated by tools/gen/webp_tables.py from the RFC 6386 tables. Do not edit.",
           "//! Values: RFC 6386 (VP8 Data Format and Decoding Guide), sections 9.6, 11.5, 13.4, 14.1.", ""]
    for src, zig, elem, shape, doc in TABLES:
        values = extract(source, src)
        total = 1
        for d in shape:
            total *= d
        if len(values) != total:
            raise SystemExit(f"{src}: expected {total} values, got {len(values)}")
        ty = "".join(f"[{d}]" for d in shape) + elem
        out.append(f"/// {doc}")
        out.append(f"pub const {zig}: {ty} = {emit(values, shape, 0)};")
        out.append("")
    lossless = open(sys.argv[1] + "/lossless.rs", encoding="utf-8").read()
    pairs = extract(lossless, "DISTANCE_MAP")
    if len(pairs) != 240:
        raise SystemExit("DISTANCE_MAP: expected 120 pairs")
    out.append("/// VP8L short distance codes 1..120 as (dx, dy) neighbourhood offsets (RFC 9649 4.2.2).")
    out.append("pub const distance_map: [120][2]i8 = .{ " +
               ", ".join(f".{{ {pairs[2 * k]}, {pairs[2 * k + 1]} }}" for k in range(120)) + " };")
    out.append("")
    sys.stdout.write("\n".join(out))


main()
