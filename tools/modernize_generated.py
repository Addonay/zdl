#!/usr/bin/env python3
"""Remove translator-only scaffolding without changing SDL's implementation."""
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
pattern=re.compile(r'(?m)^(?:pub )?(?:(?:extern|export|inline|threadlocal) )*(?:const|var|fn)\s+(@"[^"\n]+"|[A-Za-z_]\w*)')
def split(text):
    matches=list(pattern.finditer(text))
    return text[:matches[0].start()] if matches else text, {m[1]:text[m.start():matches[i+1].start() if i+1<len(matches) else len(text)] for i,m in enumerate(matches)}
def references(text):
    text=re.sub(r'(@"(?:\\.|[^"\\])*")|"(?:\\.|[^"\\])*"|//[^\n]*',lambda m:m[1] or '',text)
    return set(re.findall(r'@"[^"\n]+"|[A-Za-z_]\w*',text))

manifest=json.loads((ROOT/'translation-report/manifest.json').read_text())
active={r['output']:r for r in manifest['translations'] if r['active']}
members=parameters=0;before=after=0
for relative,record in active.items():
    if relative in ('src/SDL_list.zig','src/SDL_guid.zig'):continue
    path=ROOT/relative;original=path.read_text();before+=len(original.encode())
    # A C record has no methods. These aliases were invented by translate-c
    # and otherwise keep thousands of unrelated prototypes in each unit.
    source,count=re.subn(r'(?m)^\s+pub (?:const|var) [^\n=]+ = __root\.[^;\n]+;\n','',original)
    members+=count
    prefix,nodes=split(source)
    for name,node in list(nodes.items()):
        if not re.match(r'(?:pub )?(?:(?:export|inline) )*fn ',node) or '{\n' not in node:continue
        start=node.index('{\n')+2;header=node[:start];body=node[start:]
        aliases=list(re.finditer(r'(?m)^\s*var ([A-Za-z_]\w*) = (arg_[A-Za-z_]\w*);\n\s*_ = &\1;\n',body))
        for alias in reversed(aliases):
            local,argument=alias.groups()
            remainder=body[:alias.start()]+body[alias.end():]
            lexical=re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*','',remainder)
            assigned=re.search(r'(?<![.A-Za-z_0-9])'+re.escape(local)+r'\s*(?:[+*/%&|^<>-]*=(?!=))',lexical)
            addressed=re.search(r'&\s*\(?'+re.escape(local)+r'(?![.\[A-Za-z_0-9])',lexical)
            if assigned or addressed:continue
            replacement = local if local in references(remainder) else '_'
            header=re.sub(r'\b'+re.escape(argument)+r'(?=\s*:)',replacement,header)
            body=remainder
            parameters+=1
        nodes[name]=header+body
    source=prefix+''.join(nodes.values())
    prefix,nodes=split(source);names=set(nodes)
    roots={n for n,s in nodes.items() if re.match(r'pub export (?:fn|const|var) ',s) or re.match(r'(?:pub )?(?:threadlocal )?var ',s)}
    input_file=Path(record.get('input_file', str(ROOT/'.ref/SDL'/record['source'])))
    if input_file.is_file():
        own=input_file.read_text(errors='replace')
        functions=set(re.findall(r'(?m)^[^\n;{}]*\b(\w+)\s*\([^;{}]*\)\s*\n\{',own))
        roots.update(n for n in nodes if n in functions or n.removesuffix('_REAL') in functions)
    keep=set();todo=list(roots)
    while todo:
        name=todo.pop()
        if name in keep or name not in nodes:continue
        keep.add(name);todo.extend((references(nodes[name]) & names)-keep)
    source=prefix+''.join(s for n,s in nodes.items() if n in keep)
    source=source.replace('// Mechanically generated by zig translate-c.', '// SDL implementation ported to Zig; generated scaffolding removed.')
    path.write_text(source);after+=len(source.encode())
print(f'Removed {members} synthetic record members and {parameters} unnecessary parameter copies; '
      f'Linux implementation {before/1048576:.1f} MiB -> {after/1048576:.1f} MiB.')
